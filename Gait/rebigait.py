rng = np.random.default_rng(42)

MAX_IMPOSTOR_PAIRS = 100_000


def analyse_split(split_name):

    idx = np.where(
        meta["split"].to_numpy() == split_name
    )[0]

    split_emb = emb[idx]
    split_subjects = subjects[idx]
    split_covariates = meta["covariate"].to_numpy()[idx]

    n = len(idx)

    print("\n" + "=" * 60)
    print(split_name.upper())
    print("=" * 60)
    print("Subjects:", len(np.unique(split_subjects)))
    print("Sequences:", n)

    # --------------------------------------------------------
    # Genuine pairs
    # Same subject + different covariate
    # --------------------------------------------------------

    genuine_pairs = []

    for subject in np.unique(split_subjects):

        sidx = np.where(
            split_subjects == subject
        )[0]

        for a in range(len(sidx)):
            for b in range(a + 1, len(sidx)):

                i = sidx[a]
                j = sidx[b]

                if split_covariates[i] != split_covariates[j]:
                    genuine_pairs.append((i, j))

    genuine_pairs = np.asarray(
        genuine_pairs,
        dtype=np.int32
    )

    # Calculate genuine distances in batches.
    genuine_dist = []

    BATCH = 2000

    for start in range(0, len(genuine_pairs), BATCH):

        batch = genuine_pairs[
            start:start + BATCH
        ]

        a = split_emb[batch[:, 0]]
        b = split_emb[batch[:, 1]]

        diff = a - b

        dist = np.sqrt(
            np.sum(diff * diff, axis=1)
        )

        # Mean over 16 parts
        dist = np.mean(
            dist,
            axis=1
        )

        genuine_dist.append(dist)

    genuine_dist = np.concatenate(genuine_dist)

    # --------------------------------------------------------
    # Impostor pairs
    # Different subjects
    # --------------------------------------------------------

    subject_groups = {}

    for i, s in enumerate(split_subjects):
        subject_groups.setdefault(s, []).append(i)

    subject_names = list(subject_groups.keys())

    total_possible = 0

    for a in range(len(subject_names)):
        for b in range(a + 1, len(subject_names)):
            total_possible += (
                len(subject_groups[subject_names[a]]) *
                len(subject_groups[subject_names[b]])
            )

    sample_count = min(
        MAX_IMPOSTOR_PAIRS,
        total_possible
    )

    impostor_pairs = np.empty(
        (sample_count, 2),
        dtype=np.int32
    )

    k = 0

    while k < sample_count:

        sa, sb = rng.choice(
            len(subject_names),
            size=2,
            replace=False
        )

        i = rng.choice(
            subject_groups[subject_names[sa]]
        )

        j = rng.choice(
            subject_groups[subject_names[sb]]
        )

        impostor_pairs[k] = (i, j)
        k += 1

    impostor_dist = []

    for start in range(
        0,
        len(impostor_pairs),
        BATCH
    ):

        batch = impostor_pairs[
            start:start + BATCH
        ]

        a = split_emb[batch[:, 0]]
        b = split_emb[batch[:, 1]]

        diff = a - b

        dist = np.sqrt(
            np.sum(diff * diff, axis=1)
        )

        dist = np.mean(
            dist,
            axis=1
        )

        impostor_dist.append(dist)

    impostor_dist = np.concatenate(
        impostor_dist
    )

    print("\nGenuine:")
    print("Count:", len(genuine_dist))
    print("Mean distance:",
          round(float(np.mean(genuine_dist)), 4))
    print("Median:",
          round(float(np.median(genuine_dist)), 4))
    print("5th percentile:",
          round(float(np.percentile(genuine_dist, 5)), 4))
    print("95th percentile:",
          round(float(np.percentile(genuine_dist, 95)), 4))

    print("\nImpostor:")
    print("Count:", len(impostor_dist))
    print("Mean distance:",
          round(float(np.mean(impostor_dist)), 4))
    print("Median:",
          round(float(np.median(impostor_dist)), 4))
    print("5th percentile:",
          round(float(np.percentile(impostor_dist, 5)), 4))
    print("95th percentile:",
          round(float(np.percentile(impostor_dist, 95)), 4))

    # Lower distance = more similar.
    separation = (
        np.mean(impostor_dist) -
        np.mean(genuine_dist)
    )

    print(
        "\nMean distance separation:",
        round(float(separation), 4)
    )

    return {
        "genuine": genuine_dist,
        "impostor": impostor_dist
    }


