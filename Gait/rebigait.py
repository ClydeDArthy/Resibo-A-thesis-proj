def parse_annotation(label):

    label = re.sub(
        r"\d+$",
        "",
        str(label)
    )

    remaining = label
    components = []

    while remaining:

        for symbol in BASE_SYMBOLS:

            if remaining.startswith(symbol):

                components.append(symbol)

                remaining = remaining[
                    len(symbol):
                ]

                break

        else:
            return None

    return components


