#
# Example:
# 752-AS1-67_5_1.avi-sil.pkl
# becomes:
# 752-AS1-67_5_1.avi
# ------------------------------------------------------------
def exact_gallery_name(row):
    basename = Path(str(row["silhouette_path"])).name

    if basename.endswith("-sil.pkl"):
        basename = basename[:-len("-sil.pkl")]

    return basename


# ------------------------------------------------------------
# Gallery selection
#
# Prefer:
#   1. exact NM2
#   2. exact NM1
#   3. deterministic fallback
#
# IMPORTANT:
# Use raw_annotation here, because it retains NM1/NM2.
# ------------------------------------------------------------
def choose_gallery(manifest, subjects):

    selected = []

    for subject in sorted(subjects, key=str):

        g = manifest[
            manifest[subject_col] == str(subject)
        ].copy()

        if g.empty:
            raise ValueError(
                f"No sequences found for subject {subject}"
            )

        # Exact normal walking conditions.
        nm2 = g[g[raw_annotation_col] == "NM2"]
        nm1 = g[g[raw_annotation_col] == "NM1"]

        if not nm2.empty:
            chosen = nm2.sort_values(
                [view_col, "silhouette_path"]
            ).iloc[0]
            reason = "NM2"

        elif not nm1.empty:
            chosen = nm1.sort_values(
                [view_col, "silhouette_path"]
            ).iloc[0]
            reason = "NM1"

        else:
            # Deterministic fallback:
            # first sequence alphabetically by raw annotation,
            # then view, then actual path.
            chosen = g.sort_values(
                [
                    raw_annotation_col,
                    view_col,
                    "silhouette_path"
                ]
            ).iloc[0]
            reason = "fallback"

        gallery_name = exact_gallery_name(chosen)

        # ----------------------------------------------------
        # Verify that the selected silhouette actually exists
        # in our extracted CCGR-Mini structure.
        # ----------------------------------------------------
        actual_path = (
            sil_root
            / str(chosen[subject_col])
            / str(chosen[raw_annotation_col])
            / str(chosen[view_col])
            / Path(str(chosen["silhouette_path"])).name
        )

        if not actual_path.exists():
            raise FileNotFoundError(
                f"Gallery file not found:\n{actual_path}\n"
                f"Manifest path: {chosen['silhouette_path']}"
            )

        selected.append({
            "subject": str(subject),
            "raw_annotation": str(chosen[raw_annotation_col]),
            "normalized_annotation": str(
                chosen[normalized_annotation_col]
            ),
            "view": str(chosen[view_col]),
            "gallery_name": gallery_name,
            "selection": reason,
            "silhouette_path": str(chosen["silhouette_path"]),
            "actual_path": str(actual_path),
        })

    return pd.DataFrame(selected)


