import re

# Base symbols taken from the CCGR-Mini labeling note.
BASE_SYMBOLS = [
    "BGHV",
    "BXHV",
    "BK",
    "BG",
    "BX",
    "CR",
    "UB",
    "CL",
    "AS",
    "DN",
    "AT",
    "DT",
    "BM",
    "CV",
    "SF",
    "SD",
    "SU",
    "NM",
    "PK",
    "FD",
    "CD",
]

# Longest first prevents symbols such as BGHV from being split incorrectly.
BASE_SYMBOLS = sorted(BASE_SYMBOLS, key=len, reverse=True)

def parse_annotation(label):
    """
    Convert a CCGR-Mini annotation combination into its base symbols.
    Example: CLUBBGSD -> ['CL', 'UB', 'BG', 'SD']
    """
    if label == "SF`":
        return None

    remaining = label
    components = []

    while remaining:
        matched = False

        for symbol in BASE_SYMBOLS:
            if remaining.startswith(symbol):
                components.append(symbol)
                remaining = remaining[len(symbol):]
                matched = True
                break

        if not matched:
            return None

    return components

# Test a few known combinations.
tests = ["BK", "BGHV", "CLUB", "CVBXBG", "CLUBBGSD", "ASBXHVCL"]

for label in tests:
    print(label, "->", parse_annotation(label))

