# Recover the original subject-level split
df["subject"] = df["subject"].astype(str)

subject_split = (
    df[["subject", "split"]]
    .drop_duplicates()
)

subject_to_split = dict(
    zip(
        subject_split["subject"],
        subject_split["split"]
    )
)

meta["split"] = meta["subject"].map(subject_to_split)

# ============================================================
# PAIRWISE ANALYSIS
# ============================================================

def analyse_split(split_name):

    idx = np.where(
        meta["split"].to_numpy() == split_name
    )[0]

    local_X = X[idx]
    local_subjects = subjects[idx]
    local_covariates = meta["covariate"].to_numpy()[idx]

    # Cosine similarity because vectors are L2 normalised
    sim = local_X @ local_X.T

    i, j = np.triu_indices(
        len(idx),
        k=1
    )

    scores = sim[i, j]

    same_subject = (
        local_subjects[i] == local_subjects[j]
    )

    different_covariate = (
        local_covariates[i] != local_covariates[j]
    )

    # Genuine:
    # same person, different covariate
    genuine_mask = (
        same_subject &
        different_covariate
    )

    # Impostor:
    # different person
    impostor_mask = ~same_subject

    genuine = scores[genuine_mask]
    impostor = scores[impostor_mask]

    # Binary labels for ROC AUC
    y_true = np.concatenate([
        np.ones(len(genuine), dtype=np.int8),
        np.zeros(len(impostor), dtype=np.int8)
    ])

    y_score = np.concatenate([
        genuine,
        impostor
    ])

    auc = roc_auc_score(
        y_true,
        y_score
    )

    print("\n" + "=" * 55)
    print(split_name.upper())
    print("=" * 55)

    print("Subjects:", len(np.unique(local_subjects)))
    print("Sequences:", len(idx))

    print("\nGenuine pairs")
    print("Count:", len(genuine))
    print("Mean:", round(float(np.mean(genuine)), 4))
    print("Median:", round(float(np.median(genuine)), 4))
    print("5th percentile:",
          round(float(np.percentile(genuine, 5)), 4))
    print("95th percentile:",
          round(float(np.percentile(genuine, 95)), 4))

    print("\nImpostor pairs")
    print("Count:", len(impostor))
    print("Mean:", round(float(np.mean(impostor)), 4))
    print("Median:", round(float(np.median(impostor)), 4))
    print("5th percentile:",
          round(float(np.percentile(impostor, 5)), 4))
    print("95th percentile:",
          round(float(np.percentile(impostor, 95)), 4))

    print("\nMean separation:",
          round(
              float(np.mean(genuine) - np.mean(impostor)),
              4
          ))

    print("Pairwise ROC-AUC:",
          round(float(auc), 4))

    return {
        "genuine": genuine,
        "impostor": impostor,
        "auc": float(auc)
    }


