def extract_parsing_features(par):

    par = np.asarray(
        par,
        dtype=np.uint8
    )

    if par.ndim != 3:
        raise ValueError(
            f"Unexpected parsing shape: {par.shape}"
        )

    T = par.shape[0]

    frame_histograms = np.zeros(
        (T, 256),
        dtype=np.float32
    )

    # Normalised pixel-value histogram for each frame
    for t in range(T):

        hist = np.bincount(
            par[t].ravel(),
            minlength=256
        ).astype(np.float32)

        hist /= np.maximum(
            hist.sum(),
            1.0
        )

        frame_histograms[t] = hist

    # Sequence-level statistics
    mean_hist = frame_histograms.mean(axis=0)
    std_hist = frame_histograms.std(axis=0)

    # Temporal change in parsing distribution
    if T > 1:
        temporal_change = np.abs(
            np.diff(
                frame_histograms,
                axis=0
            )
        ).mean(axis=0)
    else:
        temporal_change = np.zeros(
            256,
            dtype=np.float32
        )

    return np.concatenate([
        mean_hist,
        std_hist,
        temporal_change
    ]).astype(np.float32)


