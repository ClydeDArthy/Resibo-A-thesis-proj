def apply_region_mask(
    sequence,
    start_ratio,
    end_ratio
):
    """
    Mask a vertical region of the detected silhouette.

    The region is defined relative to the silhouette
    bounding box for each frame.
    """

    sequence = np.asarray(
        sequence,
        dtype=np.uint8
    )

    output = sequence.copy()

    for t in range(len(sequence)):

        frame = sequence[t]

        ys, xs = np.where(
            frame > 0
        )

        if len(ys) == 0:
            continue

        top = ys.min()
        bottom = ys.max()

        height = max(
            bottom - top + 1,
            1
        )

        y_start = int(
            top + start_ratio * height
        )

        y_end = int(
            top + end_ratio * height
        )

        y_start = max(
            top,
            min(y_start, bottom)
        )

        y_end = max(
            y_start,
            min(y_end, bottom + 1)
        )

        output[
            t,
            y_start:y_end,
            :
        ] = 0

    return output


