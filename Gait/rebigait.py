def extract_pose_features(pose):

    pose = np.asarray(pose, dtype=np.float32)

    if pose.ndim != 2 or pose.shape[1] != 56:
        raise ValueError(
            f"Unexpected pose shape: {pose.shape}"
        )

    # First 4 values = bounding box
    x1 = pose[:, 0]
    y1 = pose[:, 1]
    x2 = pose[:, 2]
    y2 = pose[:, 3]

    bbox_w = np.maximum(x2 - x1, 1.0)
    bbox_h = np.maximum(y2 - y1, 1.0)

    # Remaining 51 values = 17 keypoints × (x, y, confidence)
    kp = pose[:, 5:].reshape(-1, 17, 3)

    x = kp[:, :, 0]
    y = kp[:, :, 1]
    conf = kp[:, :, 2]

    # Normalize keypoints relative to person bounding box
    x_norm = (x - x1[:, None]) / bbox_w[:, None]
    y_norm = (y - y1[:, None]) / bbox_h[:, None]

    x_norm = np.clip(x_norm, -2, 3)
    y_norm = np.clip(y_norm, -2, 3)

    # Temporal movement
    dx = np.diff(x_norm, axis=0)
    dy = np.diff(y_norm, axis=0)

    features = []

    # Position + confidence statistics
    for arr in [x_norm, y_norm, conf]:
        features.append(np.mean(arr, axis=0))
        features.append(np.std(arr, axis=0))

    # Motion statistics
    if len(dx) > 0:
        features.extend([
            np.mean(np.abs(dx), axis=0),
            np.mean(np.abs(dy), axis=0),
            np.std(dx, axis=0),
            np.std(dy, axis=0)
        ])
    else:
        zero = np.zeros(17, dtype=np.float32)
        features.extend([zero, zero, zero, zero])

    # Sequence-level statistics
    features.append(
        np.array([
            len(pose),
            np.mean(conf),
            np.std(conf),
            np.mean(np.abs(dx)) if len(dx) else 0.0,
            np.mean(np.abs(dy)) if len(dy) else 0.0
        ], dtype=np.float32)
    )

    return np.concatenate(features).astype(np.float32)


