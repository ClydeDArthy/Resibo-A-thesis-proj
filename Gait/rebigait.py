# ============================================================
# OFFICIAL CCGR-STYLE EUCLIDEAN DISTANCE
# ============================================================

def gait_distance(a, b):
    """
    Match CCGR/OpenGait's cuda_dist(..., metric='euc'):

    - a, b: (N, 256, 16)
    - Euclidean distance independently for each horizontal part
    - average over the 16 parts
    """

    diff = a[:, None, :, :] - b[None, :, :, :]

    dist_per_part = np.sqrt(
        np.sum(diff * diff, axis=2)
    )

    return np.mean(
        dist_per_part,
        axis=2
    )


