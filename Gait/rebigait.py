from pathlib import Path
import yaml

repo = Path("/content/CCGR-Official")
opt_dir = Path(
    "/content/RESIBO/experiments/"
    "12_gait_optimization"
)

configs = {
    "GaitSet": repo / "configs/gaitset/gaitset_CCGR_MINI.yaml",
    "GaitPart": repo / "configs/gaitpart/gaitpart_CCGR_MINI.yaml",
    "GaitGL": repo / "configs/gaitgl/gaitgl_CCGR_MINI.yaml",
}

for model_name, source_path in configs.items():
    assert source_path.exists(), (
        f"Missing official config: {source_path}"
    )

print("=" * 70)
print("CREATING 10K CONTROLLED BENCHMARK CONFIGS")
print("=" * 70)

for model_name, source_path in configs.items():

    with open(source_path, "r") as f:
        cfg = yaml.safe_load(f)

    # --------------------------------------------------------
    # DATA
    # --------------------------------------------------------

    cfg["data_cfg"]["dataset_name"] = "CCGR-MINI"

    cfg["data_cfg"]["dataset_root"] = (
        "/content/ccgr_mini_sil_full"
    )

    cfg["data_cfg"]["dataset_partition"] = (
        "./datasets/CCGR-MINI/"
        "CCGR-MINI-active.json"
    )

    cfg["data_cfg"]["num_workers"] = 2
    cfg["data_cfg"]["data_in_use"] = "sil"
    cfg["data_cfg"]["remove_no_gallery"] = False
    cfg["data_cfg"]["test_dataset_name"] = "CCGR-MINI"

    # --------------------------------------------------------
    # EVALUATOR
    # --------------------------------------------------------

    cfg["evaluator_cfg"]["enable_float16"] = True
    cfg["evaluator_cfg"]["restore_ckpt_strict"] = True

    # Evaluation checkpoint will be supplied later.
    cfg["evaluator_cfg"]["restore_hint"] = 0

    cfg["evaluator_cfg"]["eval_func"] = (
        "evaluate_CCGR_MINI"
    )

    cfg["evaluator_cfg"]["metric"] = "euc"

    cfg["evaluator_cfg"]["sampler"] = {
        "batch_size": 1,
        "sample_type": "all_ordered",
        "type": "InferenceSampler",
        "batch_shuffle": False,
        "frames_all_limit": 720,
    }

    cfg["evaluator_cfg"]["transform"] = [
        {
            "type": "BaseSilCuttingTransform"
        }
    ]

    # --------------------------------------------------------
    # MODEL-SPECIFIC ADJUSTMENTS
    # --------------------------------------------------------

    if model_name == "GaitGL":
        # Official CCGR-Mini config has 571 classes because
        # its original benchmark partition has 571 training IDs.
        # Our custom training split has 679.
        cfg["model_cfg"]["class_num"] = 679

        # Single GPU does not need synchronized BN.
        cfg["trainer_cfg"]["sync_BN"] = False

    # GaitSet/GaitPart do not expose a class_num field
    # in their official CCGR-Mini configs.

    # --------------------------------------------------------
    # 10K CONTROLLED TRAINING BUDGET
    # --------------------------------------------------------

    cfg["trainer_cfg"]["enable_float16"] = True
    cfg["trainer_cfg"]["with_test"] = False

    cfg["trainer_cfg"]["restore_ckpt_strict"] = True
    cfg["trainer_cfg"]["restore_hint"] = 0

    cfg["trainer_cfg"]["save_iter"] = 10000
    cfg["trainer_cfg"]["total_iter"] = 10000

    cfg["trainer_cfg"]["save_name"] = (
        f"{model_name}_CCGR_MINI_10K"
    )

    # --------------------------------------------------------
    # T4-SAFE SAMPLING
    #
    # Official configs use [8,16], but that is unnecessarily
    # expensive for this controlled comparison on one T4.
    # --------------------------------------------------------

    sampler = cfg["trainer_cfg"]["sampler"]

    sampler["batch_size"] = [4, 4]
    sampler["frames_num_fixed"] = 30

    # Keep the architecture-specific sampling style.
    # Only cap sequence lengths for the single-GPU run.
    sampler["frames_num_max"] = 40
    sampler["frames_num_min"] = 20

    # --------------------------------------------------------
    # COMPRESSED LEARNING-RATE SCHEDULE
    #
    # Official schedule:
    # 30k / 55k / 65k over an 80k run.
    #
    # For a 10k controlled run, compress those milestones
    # proportionally.
    # --------------------------------------------------------

    cfg["scheduler_cfg"]["milestones"] = [
        3750,
        6875,
        8125,
    ]

    # --------------------------------------------------------
    # OUTPUT
    # --------------------------------------------------------

    output_path = (
        opt_dir /
        f"{model_name.lower()}_CCGR_MINI_10k.yaml"
    )

    with open(output_path, "w") as f:
        yaml.safe_dump(
            cfg,
            f,
            sort_keys=False
        )

    print(
        f"✓ {model_name}:"
        f" {output_path}"
    )

print("\nAll benchmark configs created.")

